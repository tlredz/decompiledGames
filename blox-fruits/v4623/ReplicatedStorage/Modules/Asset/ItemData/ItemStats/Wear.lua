for k in pairs(Wear) do
	for i = 1, 5 do
		local v = Wear[k][i]

		if not v then
			break
		end

		if v[2].Damage then
			v[2].AllDamage = v[2].AllDamage or {}

			if v[2].AllDamage.All then
				v[2].AllDamage.All = tostring(v[2].AllDamage.All) .. "*" .. v[2].Damage
			else
				v[2].AllDamage.All = "*" .. 1 + v[2].Damage
			end

			v[2].Damage = nil
		end

		if not v[2].Cooldown then
			continue
		end

		if v[2].SwordCooldown then
			v[2].AllCooldown = tostring(v[2].AllCooldown) .. "*" .. 1 + v[2].Cooldown
		else
			v[2].AllCooldown = "*" .. 1 + v[2].Cooldown
		end

		v[2].Cooldown = nil
	end
end

