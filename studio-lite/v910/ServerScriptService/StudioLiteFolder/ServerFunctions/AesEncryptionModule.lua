			end

			assert(v6, "Counter value length must be between 1 and 16 bytes")
			clone.Prefix = convertType(clone.Prefix or {})
			clone.Suffix = convertType(clone.Suffix or {})
			assert(#clone.Prefix + #clone.Suffix + length == 16, "Counter must be 16 bytes long")
			clone.InitValue = clone.InitValue == nil and { 1 } or table.clone(convertType(clone.InitValue))
			assert(#clone.InitValue <= length, "Initial value length must be of the counter value")
			local initOverflow

