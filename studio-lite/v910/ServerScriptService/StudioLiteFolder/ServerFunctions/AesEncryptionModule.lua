			else
				initOverflow = table.clone(convertType(clone.InitOverflow))
			end

			clone.InitOverflow = initOverflow
			assert(#clone.InitOverflow <= length, "Initial overflow value length must be of the counter value")

			for _ = 1, length - #clone.InitValue do
				table.insert(clone.InitValue, (littleEndian and #clone.InitValue or 0) + 1, 0)
			end

			for _ = 1, length - #clone.InitOverflow do
				table.insert(clone.InitOverflow, (littleEndian and #clone.InitOverflow or 0) + 1, 0)
			end
		elseif type(clone) ~= "function" then
			local initValue

			if clone then
				initValue = convertType(clone)
			else
				initValue = table.create(16, 0)
			end

