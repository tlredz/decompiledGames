local function convertType(value)
	if type(value) == "string" then
		local v4 = {}

		for i = 1, string.len(value), 7997 do
			table.move({ string.byte(value, i, i + 7996) }, 1, 7997, i, v4)
		end

		return v4
	else
		if type(value) ~= "table" then
			error("Unable to cast value to bytes")
			return
		end

		for _, item in ipairs(value) do
			local v4

			if type(item) == "number" and math.floor(item) == item and item >= 0 then
				v4 = item < 256
			else
				v4 = false
			end

			assert(v4, "Unable to cast value to bytes")
		end

		return value
	end
end

local function init(p, p2, p3, clone, value)
