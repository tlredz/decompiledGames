local countryNames = {}

for _, country in next, CountryData.Countries, nil do
	table.insert(countryNames, country.CountryName)
end

table.sort(countryNames, function(a: string, b: string)
	return a:lower() < b:lower()
end)

for _, country in next, CountryData.Countries, nil do
	country.CountryIndex = table.find(countryNames, country.CountryName)

	if country.CountryName == "United States" then
		country.CountryIndex = -1
	end
end

function CountryData.GetFlagEmoji(value)
	if not value then
		return ""
	end

	if #value ~= 2 then
		return "🏳"
	end

	local v = string.byte(value, 1) - 65 + 127462
	local v2 = string.byte(value, 2) - 65 + 127462
	return utf8.char(v, v2)
end

function CountryData.GetCountryInfo(p: string)
	if not p then
		return nil
	end

	if CountryData.Countries[p] then
		return {
			BigTitle = CountryData.Countries[p].CountryName,
			CountryIndex = CountryData.Countries[p].CountryIndex
		}
	end

	return nil
end

return CountryData