local function GetSuffix(p)
	if p == 0 then
		return "UTC"
	end

	local v2 = p > 0 and "+" or "-"
	local v3 = math.abs(p)
	local v4 = math.floor(v3 / 60)
	local v5 = v3 % 60

	if v5 > 0 then
		return string.format("UTC%s%d:%02d", v2, v4, v5)
	end

	return string.format("UTC%s%d", v2, v4)
end

local function FormatTimestamp(p)
	local v2 = os.date("*t", p)
	return string.format(
		"%s %d, %d at %02d:%02d %s",
		os.date("%B", p),
		v2.day,
		v2.year,
		(v2.hour - 1) % 12 + 1,
		v2.min,
		v2.hour >= 12 and "PM" or "AM"
	)
end

local function FormatTimestamp_Thai(p)
	local v2 = os.date("*t", p)
	return string.format("%d %s %d เวลา %02d:%02d น.", v2.day, ({
		"มกราคม",
		"กุมภาพันธ์",
		"มีนาคม",
		"เมษายน",
		"พฤษภาคม",
		"มิถุนายน",
		"กรกฎาคม",
		"สิงหาคม",
		"กันยายน",
		"ตุลาคม",
		"พฤศจิกายน",
		"ธันวาคม"
	})[v2.month], v2.year, v2.hour, v2.min)
end

