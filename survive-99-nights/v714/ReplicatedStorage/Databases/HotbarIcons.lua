function HotbarIcons.GetIconColour(instance)
	local iconColour = instance:GetAttribute("IconColour")

	if iconColour then
		return HotbarIcons.Colours[iconColour]
	end

	local heal = HotbarIcons.IconColours[instance.Name]

	if heal == nil and instance:GetAttribute("ToolName") then
		heal = HotbarIcons.IconColours[instance:GetAttribute("ToolName")]
	end

	if heal == nil and (instance:GetAttribute("RestoreHealth") or 0) >= 40 then
		heal = HotbarIcons.Colours.Heal
	end

	return heal
end

