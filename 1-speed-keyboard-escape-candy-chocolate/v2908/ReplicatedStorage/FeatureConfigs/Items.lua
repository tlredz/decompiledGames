	if type(p) ~= "table" or type(p.Limited) ~= "number" or p.Limited ~= p.Limited or math.abs(p.Limited) == 1e999 then
		return nil
	end

	local limited = math.floor(p.Limited)

	if limited >= 1 then
		return limited
	end

	return nil
end

function Items.MaxLimitedOf(p)
	if type(p) ~= "table" or type(p.MaxLimited) ~= "number" or p.MaxLimited ~= p.MaxLimited or math.abs(p.MaxLimited) == 1e999 then
		return nil
	end

	local maxLimited = math.floor(p.MaxLimited)

	if maxLimited >= 1 then
		return maxLimited
	end

	return nil
end

function Items.SignatureOf(p)
	if type(p) == "table" and type(p.Signature) == "number" and p.Signature == p.Signature and math.abs(p.Signature) ~= 1e999 and p.Signature ~= 0 and p.Signature % 1 == 0 then
		return p.Signature
	end

	return nil
end

function Items.IsLimitedKey(p: string)
	local v = Items.ITEMS[p]
	return v ~= nil and type(v.limited) == "number" and v.limited == v.limited and math.abs(v.limited) ~= 1e999 and v.limited == math.floor(v.limited) and v.limited >= 1
end

function Items.IsLimitedEntry(p)
	local isLimitedKey = Items.IsLimitedKey(Items.KeyOf(p))

	if isLimitedKey then
		if Items.LimitedNumberOf(p) == nil then
			isLimitedKey = false
		else
			isLimitedKey = Items.MaxLimitedOf(p) ~= nil
		end
	end

	return isLimitedKey
end

function Items.Entry(p: string, value: number, p2: number?, p3: number?, signature: number?)
	local v = {
		Key = p,
		Tier = math.clamp(math.floor(value or 0), 0, Items.MAX_TIER)
	}

	if Items.IsLimitedKey(p) and p2 ~= nil and p3 ~= nil then
		v.Limited = math.max(1, (math.floor(p2)))
		v.MaxLimited = math.max(1, (math.floor(p3)))
	end

	if type(signature) == "number" and signature == signature and math.abs(signature) ~= 1e999 and signature ~= 0 and signature % 1 == 0 then
		v.Signature = signature
	end

	return v
end

function Items.CopyEntry(p)
	return Items.Entry(
		Items.KeyOf(p),
		Items.TierOf(p),
		Items.LimitedNumberOf(p),
		Items.MaxLimitedOf(p),
		Items.SignatureOf(p)
	)
end

function Items.EntriesMatch(p, p2)
	if Items.KeyOf(p) ~= Items.KeyOf(p2) or Items.TierOf(p) ~= Items.TierOf(p2) then
		return false
	end

	if Items.IsLimitedKey(Items.KeyOf(p)) and (Items.LimitedNumberOf(p) == nil or Items.LimitedNumberOf(p) ~= Items.LimitedNumberOf(p2) or Items.MaxLimitedOf(p) ~= Items.MaxLimitedOf(p2)) then
		return false
	end

	return Items.SignatureOf(p) == Items.SignatureOf(p2)
end

function Items.GetTieredMultiplier(p: number, p2: number)
	return p + p2 * math.log(p + 2.0137527074704766 - 1) * 1.5
end

function Items.EntryMultiplier(p)
	local key = Items.KeyOf(p)
	local v = Items.ITEMS[key]

	if v then
		return Items.GetTieredMultiplier(v.multiplier, Items.TierOf(p))
	end

	return 0
end

function Items.EntryBonusPercent(p)
	return (math.floor(Items.EntryMultiplier(p) * 100 + 0.5))
end

function Items.Normalize(list)
	local result = {}

	if type(list) ~= "table" then
		return result
	end

	for _, v in ipairs(list) do
		local key = nil
		local tier = 0

		if type(v) == "string" then
			key = v
		elseif type(v) == "table" and type(v.Key) == "string" then
			key = v.Key
			tier = tonumber(v.Tier) or 0
		end

		if key and Items.ITEMS[key] then
			table.insert(
				result,
				Items.Entry(key, tier, Items.LimitedNumberOf(v), Items.MaxLimitedOf(v), Items.SignatureOf(v))
			)
		end
	end

	return result
end

function Items.ToKeys(list)
	local result = {}

	if type(list) ~= "table" then
		return result
	end

	for _, v in ipairs(list) do
		table.insert(result, v.Key)
	end

	return result
end

function Items.GetTotalMultiplier(list)
	local total = 0

	for _, v in ipairs(list) do
		total += Items.EntryMultiplier(v)
	end

	return total + 1
end

function Items.GetTotalBonusPercent(list)
	local total = 0

	for _, v in ipairs(list) do
		total += Items.EntryMultiplier(v)
	end

	return (math.floor(total * 100 + 0.5))
end

Items.RARITY_PRIORITY = {
	Unreal = 0,
	Exotic = 1,
	Secret = 2,
	Mythic = 3,
	Legendary = 4,
	Epic = 5,
	Rare = 6,
	Uncommon = 7,
	Common = 8
}

function Items.SortByBest(p)
	local clone = table.clone(p)
	table.sort(clone, function(a, b)
		local entryMultiplier = Items.EntryMultiplier(a)
		local entryMultiplier2 = Items.EntryMultiplier(b)

		if entryMultiplier ~= entryMultiplier2 then
			return entryMultiplier2 < entryMultiplier
		end

		local v = Items.ITEMS[a.Key]
		local v2 = Items.ITEMS[b.Key]
		return (Items.RARITY_PRIORITY[v and v.rarity or "Common"] or 8) < (Items.RARITY_PRIORITY[v2 and v2.rarity or "Common"] or 8)
	end)
	return clone
end

function Items.GetItemsByRarity(p: string)
	local result = {}

	for k, v in pairs(Items.ITEMS) do
		if v.rarity == p then
			table.insert(result, k)
		end
	end

	return result
end

